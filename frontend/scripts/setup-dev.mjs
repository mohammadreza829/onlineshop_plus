// Local development bootstrap only. Production never invokes this script.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { parseEnv } from "node:util";
import { randomBytes } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
if (process.env.NODE_ENV === "production")
  throw new Error("Automatic setup is development-only.");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const file = resolve(root, ".env.local");
const defaults = {
  APP_ORIGIN: "http://127.0.0.1:3000",
  DJANGO_ORIGIN: "http://127.0.0.1:8000",
  BFF_COOKIE_SECRET: randomBytes(48).toString("base64url"),
  BFF_REDIS_URL: "",
  BFF_COORDINATION: "memory",
  PAYMENT_HOSTS: "sandbox.zarinpal.com",
};
mkdirSync(root, { recursive: true });
const configs = [
  ".env",
  ".env.development",
  ".env.local",
  ".env.development.local",
];
let choices = {};
for (const name of configs) {
  const path = resolve(root, name);
  if (existsSync(path)) {
    try {
      choices = { ...choices, ...parseEnv(readFileSync(path, "utf8")) };
    } catch {
      console.error(
        "Local environment file cannot be parsed. No values printed.",
      );
      process.exit(1);
    }
  }
}
choices = { ...choices, ...process.env };
let text = existsSync(file)
  ? readFileSync(file, "utf8")
  : "# Local development only. Generated by setup:dev; never commit.\n";
const original = text;
for (const [key, value] of Object.entries(defaults)) {
  if (
    choices[key] !== undefined &&
    !(key === "BFF_COOKIE_SECRET" && choices[key] === "")
  )
    continue;
  // Do not shadow an explicit process/higher-priority empty secret; doctor will report it.
  if (
    key === "BFF_COOKIE_SECRET" &&
    (process.env[key] !== undefined ||
      (existsSync(resolve(root, ".env.development.local")) &&
        key in
          parseEnv(
            readFileSync(resolve(root, ".env.development.local"), "utf8"),
          )))
  )
    continue;
  const match = text.match(
    new RegExp(`^\\s*(?:export\\s+)?${key}\\s*=[^\\r\\n]*$`, "m"),
  );
  if (match) text = text.replace(match[0], `${key}=${value}`);
  else text += `\n${key}=${value}\n`;
}
if (!existsSync(file) || text !== original)
  writeFileSync(file, text, { mode: 0o600 });
console.log(
  "Local development configuration checked; existing choices preserved. No secrets printed.",
);
